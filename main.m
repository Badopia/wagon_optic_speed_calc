format long;                                  % Включаем длинный формат вывода чисел
format compact;                               % Убираем лишние пустые строки в выводе
clear;                                        % Очищаем рабочее пространство

% Датчики и их расположение
delta = 50;                                   % Расстояние между двумя датчиками вдоль пути, см
h = 40;                                       % Высота датчика над поверхностью для расчёта размера пятна, см
T = 5;                                        % Длительность записи, с
d0 = 0.40;                                    % Принятый боковой зазор от датчика до плоскости борта, м

speed = 5;                                    % Начальная скорость вагона, м/с
acceleration = 0.5;                           % Ускорение вагона, м/с^2

% Параметры датчиков

% DE-CM2THIU
sensors(1).name = 'DE-CM2THIU';               % Название датчика
sensors(1).frekvence = 10;                    % Время отклика датчика, мс
sensors(1).FoV = 2;                           % Дальность действия датчика (Field of View), м
sensors(1).std = 0.003;                       % Стандартное отклонение шума (линейная точность 0.3% F.S.)

profileFile = 'data/wagon_12_6995_profile.mat';  % Путь к файлу с профилем вагона
S = load(profileFile, 'profile');             % Загружаем переменную profile из MAT-файла

xProfile = S.profile.x_m;                     % Координата вдоль вагона, м
depthProfile = S.profile.depth_from_side_m;   % Глубина от плоскости борта, м

%% Движение вагона

L = delta / 100;                              % Переводим расстояние между дальномерами из см в м
Ts = 0.010;                                   % Шаг записи для модели, с
t = (0:Ts:T).';                               % Общая шкала времени обоих датчиков, с (столбец)

s = speed * t + 0.5 * acceleration * t.^2;    % Пройденный путь вагона, м
vTrue = speed + acceleration * t;             % Истинная скорость вагона в каждый момент времени, м/с

x1 = s;                                       % Координата профиля напротив первого датчика, м
x2 = s - L;                                   % Координата профиля напротив второго датчика, м

%% Показания двух одинаковых дальномеров

% Интерполируем профиль. Вне его границ считаем, что возврата нет.
y1 = d0 + interp1(xProfile, depthProfile, x1, 'linear', 2);  % Показания первого датчика: зазор + глубина профиля
y2 = d0 + interp1(xProfile, depthProfile, x2, 'linear', 2);  % Показания второго датчика: тот же профиль со сдвигом L

% Добавляем независимый шум к показаниям каждого датчика.
y1 = y1 + sensors(1).std * randn(size(y1));   % Добавляем гауссов шум к сигналу первого датчика
y2 = y2 + sensors(1).std * randn(size(y2));   % Добавляем независимый гауссов шум к сигналу второго датчика

% Отсчёты вне диапазона дальномера считаем пропусками.
maxRange = sensors(1).FoV*0.995;              % Максимальная допустимая дальность с небольшим запасом, м
y1(y1 <= 0 | y1 > maxRange) = 2;              % Всё вне диапазона первого датчика заменяем на фон 2 м
y2(y2 <= 0 | y2 > maxRange) = 2;              % Всё вне диапазона второго датчика заменяем на фон 2 м


%% Автоматическое выделение деталей по сигналу первого датчика

bg = 2.00;                                    % Фон на графике дальномеров, м
threshold = 0.1;                              % Минимальный уход с фона, м
minSamples = ceil(0.05 / Ts);                 % Минимум 0,05 с на деталь (в отсчётах)
pad = round(0.03 / Ts);                       % Запас с обеих сторон детали (в отсчётах)

active = y1(:) < bg - threshold;              % Логический вектор: где первый датчик видит деталь
edges = diff([0; double(active); 0]);         % Переходы 0→1 и 1→0 дают начало и конец деталей

iStart = find(edges == 1);                    % Индексы начала активных участков
iEnd = find(edges == -1) - 1;                 % Индексы конца активных участков

keep = iEnd - iStart + 1 >= minSamples;       % Оставляем только достаточно длинные детали
iStart = max(1, iStart(keep) - pad);          % Расширяем начало деталей на pad, не выходя за границы
iEnd = min(numel(y1), iEnd(keep) + pad);      % Расширяем конец деталей на pad, не выходя за границы

%% Оценка скорости для каждой детали

vMin = 4;                                     % Нижняя граница поиска скорости, м/с
vMax = 8;                                     % Верхняя граница поиска скорости, м/с
lags = ceil(L / (vMax * Ts)):floor(L / (vMin * Ts));  % Возможные запаздывания между датчиками в отсчётах

tau = nan(size(iStart));                      % Массив для найденных задержек, с
v = nan(size(iStart));                        % Массив для найденных скоростей, м/с
peak = nan(size(iStart));                     % Массив для максимальной корреляции

for k = 1:numel(iStart)                       % Цикл по всем выделенным деталям
    idx = iStart(k):iEnd(k);                  % Индексы текущей детали в сигнале первого датчика
    if idx(end) + lags(end) > numel(y2)       % Проверяем, что для второго датчика хватает данных
        continue                              % Если данных мало — пропускаем деталь
    end

    a = y1(idx);                              % Фрагмент сигнала первого датчика для текущей детали
    c = nan(size(lags));                      % Массив для коэффициентов корреляции при разных lag

    for j = 1:numel(lags)                     % Перебираем все допустимые запаздывания
        b = y2(idx + lags(j));                % Соответствующий фрагмент второго датчика со сдвигом lag
        R = corrcoef(a, b);                   % Считаем корреляционную матрицу двух фрагментов
        c(j) = R(1, 2);                       % Берём коэффициент корреляции между a и b
    end

    [peak(k), jBest] = max(c, [], 'omitnan'); % Находим максимальную корреляцию и её индекс
    if peak(k) >= 0.80                        % Принимаем результат, только если корреляция достаточно высокая
        tau(k) = lags(jBest) * Ts;            % Переводим найденный lag в секунды
        v(k) = L / tau(k);                    % Скорость = расстояние между датчиками / задержка
    end
end

%% Просмотр сигналов
figure                                        % Создаём новое графическое окно
plot(t, y1, 'LineWidth', 1.3,'Color','black')                 % Строим сигнал первого датчика
hold on                                       % Оставляем график для наложения второго сигнала
plot(t, y2, 'LineWidth', 1.3,'Color','red')                 % Строим сигнал второго датчика
grid on                                       % Включаем сетку
xlabel('Время, с')                            % Подпись оси X
ylabel('Расстояние до поверхности вагона, м') % Подпись оси Y

xline(t(iStart),'b')
xline(t(iEnd),'--b')
legend('Датчик 1', 'Датчик 2', 'Location', 'best')  % Легенда с автоматическим размещением


results = table(t(iStart), t(iEnd), tau, v, peak, ...  % Формируем таблицу результатов
    'VariableNames', {'Start_s', 'End_s', 'Delay_s', 'Speed_mps', 'Correlation'})  % Задаём имена столбцов