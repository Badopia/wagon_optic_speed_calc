% Просмотр продольного профиля полувагона 12-6995 на высоте датчиков.
scriptFolder = fileparts(mfilename('fullpath'));
profileFile = fullfile(scriptFolder, 'data', 'wagon_12_6995_profile.mat');
if ~isfile(profileFile)
    error('Файл профиля не найден: %s', profileFile);
end

data = load(profileFile, 'profile');
profile = data.profile;

profileFigure = figure('Name', ['Профиль полувагона ' profile.wagon_type], ...
    'NumberTitle', 'off');
ax = axes(profileFigure);
plot(ax, profile.x_m, profile.depth_from_side_m, ...
    'LineWidth', 1.6, 'DisplayName', 'Профиль');
yline(ax, profile.background_depth_from_side_m, '--', ...
    'DisplayName', 'Условный фон');
xlim(ax, [profile.x_m(1), profile.x_m(end)]);
grid(ax, 'on');

title(ax, ['Профиль полувагона ' profile.wagon_type ' на высоте датчиков']);
xlabel(ax, 'Координата от левой концевой балки, м');
ylabel(ax, 'Глубина относительно нуля профиля, м');
legend(ax, 'Location', 'best');

% --- Описание кода -------------------------------------------------------
% Назначение: скрипт строит продольный профиль полувагона 12-6995 на
% высоте датчиков, то есть распределение глубины поверхности вагона вдоль
% его длины. Используется для визуальной оценки рельефа, который увидит
% оптическая система измерения (например, для расчёта профиля загрузки).
%
% Входные данные: файл data/wagon_12_6995_profile.mat в папке скрипта,
% который содержит структуру profile с полями:
%   wagon_type                    - обозначение модели вагона (для заголовков);
%   x_m                           - координата вдоль вагона от левой концевой
%                                   балки, м (вектор);
%   depth_from_side_m             - глубина поверхности относительно нуля
%                                   профиля, м (вектор той же длины, что x_m);
%   background_depth_from_side_m  - уровень условного фона, м (скаляр).
%
% Логика работы:
%   1. Папка скрипта определяется по mfilename, поэтому запуск не зависит
%      от текущей рабочей папки MATLAB.
%   2. Проверяется наличие .mat-файла; при отсутствии выдаётся ошибка с
%      полным путём, а не невнятный сбой load.
%   3. Из файла загружается только переменная profile.
%   4. Строится график depth_from_side_m(x_m) с линией условного фона,
%      диапазоном координаты строго по данным, сеткой, подписями осей
%      и легендой; заголовок включает тип вагона из данных.
%
% Результат: объект figure с осями ax; сами данные не изменяются.
% Требования: базовый MATLAB (графические функции), других продуктов нет.
% --------------------------------------------------------------------------
